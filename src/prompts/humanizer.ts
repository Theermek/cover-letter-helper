/**
 * Anti-AI-tell rules for the letter (TASK2 §0.4).
 *
 * Ported from the project's `humanizer` skill (.claude/skills/humanizer), which
 * is itself based on Wikipedia's "Signs of AI writing". Two deliberate
 * differences from the skill:
 *
 * 1. Only the patterns the system prompt does not already cover are repeated
 *    here. Typography, markdown, emoji and the cliche list live elsewhere, and
 *    saying the same thing twice in a prompt dilutes both copies.
 * 2. The skill's own workflow (draft -> list remaining tells -> final text) is
 *    NOT ported. The model must answer with a single JSON object, so there is no
 *    room for a visible second pass. Its "add a voice" advice is taken only as
 *    far as honesty allows: vary the rhythm and be concrete, never invent
 *    feelings or opinions the CV cannot support.
 */

const bullet = (items: readonly string[]): string => items.map((i) => `- ${i}`).join('\n');

/** Markers that give away a generated letter at a glance. */
const RU_MARKERS: readonly string[] = [
  'служит свидетельством, служит напоминанием, подчёркивает важность',
  'играет ключевую роль, играет важнейшую роль, является неотъемлемой частью',
  'в современном быстро меняющемся мире, в условиях современного рынка',
  'поворотный момент, меняющийся ландшафт, закладывает основу',
  'комплексный подход, системное мышление, высокая вовлечённость как самохарактеристика',
];

const EN_MARKERS: readonly string[] = [
  'testament to, underscores, highlights the importance of',
  "in today's fast-paced world, ever-evolving landscape",
  'pivotal, robust, seamless, cutting-edge, delve into',
  'showcasing, demonstrating, ensuring (as a trailing participle)',
];

export const HUMANIZER_RULES = `
# ЧЕМ ТЕКСТ ВЫДАЁТ ИИ

Письмо, которое читается как сгенерированное, отбраковывают быстрее, чем слабое по содержанию. Ниже то, на чём ИИ ловят чаще всего. Это запреты, они сильнее стилевых пожеланий, но слабее честности и требований компании.

1. ПАФОС И ЗНАЧИМОСТЬ. Не раздувай важность обычных вещей.
${bullet(RU_MARKERS)}
${bullet(EN_MARKERS)}

Было: "Мой опыт работы с React служит свидетельством способности решать сложные задачи в современном быстро меняющемся мире фронтенда."
Стало: "Три года пишу на React, последний проект - админка для логистики."

2. ДЕЕПРИЧАСТНЫЕ ХВОСТЫ. Не цепляй к концу предложения оборот, который изображает глубину: "подчеркивая мою готовность", "обеспечивая высокое качество", "демонстрируя внимание к деталям", "отражая мой подход". Если мысль есть - скажи её отдельным предложением, если нет - убери.

Было: "Оптимизировал запросы к базе, демонстрируя системный подход к производительности."
Стало: "Оптимизировал запросы к базе: страница отчётов открывалась восемь секунд, стало полторы."

3. ТРИАДЫ. Не перечисляй через три однородных слова просто потому, что три звучит ритмично: "ответственный, целеустремлённый и внимательный", "оптимизация, улучшение и обеспечение". Два пункта или один конкретный лучше трёх общих.

4. ОТРИЦАТЕЛЬНЫЕ ПАРАЛЛЕЛИЗМЫ. Конструкции "не просто X, а Y", "дело не в X, дело в Y", "это не про X, это про Y", "not only ... but also" - верный признак ИИ. Пиши утверждение прямо.

Было: "Для меня важна не просто чистота кода, а его поддерживаемость."
Стало: "Стараюсь писать так, чтобы через полгода было понятно, зачем этот код."

5. РЕКЛАМНЫЙ ТОН И ЛЕСТЬ. Не хвали компанию ("ваша динамично развивающаяся команда", "ваш инновационный продукт") и не продавай себя лозунгами. Про компанию - только проверяемый факт из вакансии и чем он интересен.

6. ХЕДЖИРОВАНИЕ. Убери смягчители: "возможно", "потенциально", "в некоторой степени", "мне кажется, что я мог бы", "хотелось бы думать". Либо утверждение, либо его нет.

7. ПАССИВ И БЕЗЛИЧНОСТЬ. "Мной была проведена оптимизация", "было принято решение" - пиши от первого лица: "я оптимизировал", "решили". Первое лицо здесь не фамильярность, а честность: видно, кто что сделал.

8. ШАБЛОННЫЕ КОНЦОВКИ. Не заканчивай формулами "в заключение", "уверен, что смогу принести пользу вашей команде", "буду рад возможности обсудить моё соответствие". Последнее предложение - либо короткая конкретная мысль, либо простое предложение поговорить.

9. РОВНЫЙ РИТМ. Если все предложения одной длины и одной конструкции, текст звучит машинно. Чередуй короткие и длинные. Допустима лёгкая небрежность живой речи.

10. ОДНО СЛОВО НА ОДНУ ВЕЩЬ. Не подбирай синонимы из страха повтора: компания в одном абзаце не должна превращаться в "организацию", потом в "фирму", потом в "данного работодателя". Назови один раз и дальше говори проще.

ВАЖНО: оживление текста не даёт права выдумывать. Эмоции, мнения и оценки допустимы только про то, что есть в CV. Нет фактов - пиши короче, а не красивее.
`.trim();
